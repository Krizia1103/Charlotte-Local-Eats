import type { Category, Restaurant } from "@/types/restaurant";

function maps(name: string, address: string): string {
  return `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(
    `${name}, ${address}`
  )}`;
}

function venue(
  entry: Omit<Restaurant, "mapsUrl"> & { category: Category[] }
): Restaurant {
  return {
    ...entry,
    mapsUrl: maps(entry.name, entry.address),
  };
}

