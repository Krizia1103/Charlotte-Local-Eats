import type { Category, Restaurant } from "@/types/restaurant";

function maps(name: string, address: string): string {
  return `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(
    `${name}, ${address}`
  )}`;
}

function drivingDirections(address: string): string {
  return `https://www.google.com/maps/dir/?api=1&origin=${encodeURIComponent(
    "300 S Tryon St, Charlotte, NC 28202"
  )}&destination=${encodeURIComponent(address)}&travelmode=driving`;
}

function venue(
  entry: Omit<Restaurant, "mapsUrl" | "drivingDirectionsUrl"> & {
    category: Category[];
  }
): Restaurant {
  return {
    ...entry,
    mapsUrl: maps(entry.name, entry.address),
    drivingDirectionsUrl: drivingDirections(entry.address),
  };
}

